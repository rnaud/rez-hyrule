#!/usr/bin/env node
/**
 * Precompute the canticle's syllables with the CMU pronouncing dictionary, so the
 * game can sing correct English without shipping the 850 KB dictionary or fetching
 * it at runtime.
 *
 *   node scripts/build-canticle-lyrics.mjs
 *   CMUDICT=/path/to/cmudict.txt.gz node scripts/build-canticle-lyrics.mjs
 *
 * Needs public/chimera/chimera.wasm (scripts/build-chimera-wasm.sh). Without a
 * local dictionary the script downloads the one the engine's own page uses.
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { canticleLines } from '../src/chimera/canticle.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const WASM = path.join(ROOT, 'public/chimera/chimera.wasm');
const OUT = path.join(ROOT, 'src/chimera/lyrics.js');
const DICT_URL = 'https://raw.githubusercontent.com/jamesondh/chimera-vocal-synth/main/public/data/cmudict.txt.gz';

if (!fs.existsSync(WASM)) {
  console.error(`missing ${path.relative(ROOT, WASM)} — run scripts/build-chimera-wasm.sh first`);
  process.exit(1);
}

const enc = new TextEncoder();
const dec = new TextDecoder();
const mod = await WebAssembly.compile(fs.readFileSync(WASM));
const ex = (await WebAssembly.instantiate(mod, {})).exports;

function call(fn, args = {}) {
  const bytes = enc.encode(JSON.stringify({ fn, ...args }));
  const p = ex.chimera_alloc(bytes.length);
  new Uint8Array(ex.memory.buffer, p, bytes.length).set(bytes);
  const status = ex.chimera_call(p, bytes.length);
  ex.chimera_free(p, bytes.length);
  const out = JSON.parse(dec.decode(new Uint8Array(ex.memory.buffer, ex.chimera_result_ptr(), ex.chimera_result_len())));
  if (status !== 0) throw new Error(out.error || `engine ${fn} failed`);
  return out;
}

async function readDictionary() {
  const local = process.env.CMUDICT;
  if (local) return zlib.gunzipSync(fs.readFileSync(local)).toString('utf8');
  console.log('downloading CMUdict…');
  const res = await fetch(DICT_URL);
  if (!res.ok) throw new Error(`dictionary: HTTP ${res.status}`);
  return zlib.gunzipSync(Buffer.from(await res.arrayBuffer())).toString('utf8');
}

const entries = canticleLines();
call('g2pLoad', { text: await readDictionary() });

const table = {};
const problems = [];
for (const l of entries) {
  const syl = call('lyricsToSyllables', { text: l.text });
  table[l.text] = syl;
  if (syl.length !== l.degrees.length) {
    problems.push(`"${l.text}": ${syl.length} syllables for ${l.degrees.length} notes — ${syl.map((s) => s.text).join(' ')}`);
  }
}

const body = `/**
 * Precomputed sung syllables for the canticle (CMUdict, through the engine's own
 * front end). Generated by scripts/build-canticle-lyrics.mjs — do not edit by hand.
 * One entry per lyric line; each syllable carries its IPA onset, nucleus and coda,
 * so the engine sings the words rather than spelling them out.
 */
export const CANTICLE_SYLLABLES = ${JSON.stringify(table, null, 1)};

export function syllablesFor(text) {
  return CANTICLE_SYLLABLES[text] || null;
}
`;

fs.writeFileSync(OUT, body);
console.log(`wrote ${path.relative(ROOT, OUT)} — ${entries.length} lines, ${Object.values(table).reduce((n, s) => n + s.length, 0)} syllables`);
if (problems.length) {
  console.error('\nSyllable/note count mismatches:');
  for (const p of problems) console.error('  ' + p);
  process.exit(1);
}
